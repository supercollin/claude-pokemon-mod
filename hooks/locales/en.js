// Joins items as "A", "A or B", or "A, B, or C", and the same with and
const joined = (word) => (items) => (items.length < 3 ? items.join(' ' + word + ' ') : items.slice(0, -1).join(', ') + ', ' + word + ' ' + items.at(-1))
